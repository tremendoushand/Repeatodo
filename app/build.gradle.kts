    signingConfigs {
        create("release") {
            val storePath = signingValue("storeFile", "REPEATODO_KEYSTORE")
            if (storePath != null) {
                storeFile = rootProject.file(storePath)
                storePassword = signingValue("storePassword", "REPEATODO_KEYSTORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "REPEATODO_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "REPEATODO_KEY_PASSWORD")
